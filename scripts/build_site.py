def main():
    recs, links = load()
    byid = {r["id"]: r for r in recs}
    sims = similar_map(recs)
    gen = time.strftime("%d %b %Y")
    if DOCS.exists():
        for p in DOCS.glob("r/*.html"): p.write_text("")  # overwritten below; avoid deletes
    (DOCS / "r").mkdir(parents=True, exist_ok=True)
    (DOCS / "assets").mkdir(exist_ok=True)
    for f in ["style.css", "app.js", "theme.js"]:
        shutil.copyfile(SITE_SRC / f, DOCS / "assets" / f)
    idx = []
    for r in recs:
        s = r["summary"]
        src = r.get("sources", [])
        via = f'{short_list(src[0]["list"])}{" › " + src[0]["section"] if src[0].get("section") else ""}' if src else ""
        idx.append({"id": slug(r["repo"]), "n": r["repo"], "o": s.get("one_liner", ""), "c": s.get("category", ""),
                    "k": s.get("keywords", []), "u": s.get("use_cases", [])[:5], "g": r.get("lists", []),
                    "m": 1 if r["kind"] == "star" else 0, "s": r.get("stars", 0), "l": r.get("language", ""), "v": via[:80]})
        (DOCS / "r" / f'{slug(r["repo"])}.html').write_text(repo_page(r, links.get(r["id"], {}), sims.get(r["id"], []), byid, gen))
    (DOCS / "assets" / "index.js").write_text("window.STARS=" + json.dumps(idx, ensure_ascii=False, separators=(",", ":")) + ";")
    n_mine = sum(1 for r in recs if r["kind"] == "star")
    (DOCS / "index.html").write_text(index_page(len(recs), n_mine, gen))
    (DOCS / ".nojekyll").write_text("")
    size = sum(p.stat().st_size for p in DOCS.rglob("*") if p.is_file())
    print(f"built {len(recs)} pages into docs/ ({size/1e6:.1f} MB, index.js {(DOCS/'assets'/'index.js').stat().st_size/1e6:.1f} MB)")

if __name__ == "__main__":
    main()
